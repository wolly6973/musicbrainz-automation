def wait_for_musicbrainz():
    global last_musicbrainz_request

    elapsed = (
        time.monotonic()
        - last_musicbrainz_request
    )

    if elapsed < MB_MIN_INTERVAL:

        time.sleep(
            MB_MIN_INTERVAL - elapsed
        )

    last_musicbrainz_request = (
        time.monotonic()
    )


