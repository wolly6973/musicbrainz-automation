HARMONY_COMPLETIONS_FILE = "/opt/mb-automation/harmony_completions.json"
harmony_completion_lock = threading.Lock()


def get_harmony_completions():

    if not os.path.exists(HARMONY_COMPLETIONS_FILE):
        return []

    try:

        with open(
            HARMONY_COMPLETIONS_FILE,
            "r"
        ) as f:

            data = json.load(f)

        if isinstance(data, list):
            return data

    except Exception as error:

        print(
            f"WARNING: Could not read Harmony completion state: {error}"
        )

    return []


def save_harmony_completions(completions):

    temp_file = (
        HARMONY_COMPLETIONS_FILE +
        ".tmp"
    )

    with open(
        temp_file,
        "w"
    ) as f:

        json.dump(
            completions,
            f,
            indent=2,
        )

    os.replace(
        temp_file,
        HARMONY_COMPLETIONS_FILE,
    )


@app.route(
    "/harmony-release-jobs",
    methods=["GET"]
)
def harmony_release_jobs():

    with harmony_completion_lock:

        completions = get_harmony_completions()

    return jsonify({
        "ok": True,
        "jobs": completions,
    })


@app.route(
    "/harmony-release-job/claim",
    methods=["POST"]
)
def harmony_release_job_claim():

    data = request.get_json(
        silent=True
    ) or {}

    release_mbid = str(
        data.get(
            "release_mbid",
            ""
        )
    ).strip()

    if not release_mbid:

        return jsonify({
            "ok": False,
            "error": "Missing release_mbid",
        }), 400

    if not re.fullmatch(
        r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}",
        release_mbid,
    ):

        return jsonify({
            "ok": False,
            "error": "Invalid release_mbid",
        }), 400

    with harmony_completion_lock:

        completions = get_harmony_completions()

        existing = next(
            (
                item
                for item in completions
                if item.get("release_mbid") == release_mbid
            ),
            None,
        )

        if not existing:

            return jsonify({
                "ok": False,
                "error": "Release job not found",
            }), 404

        current_status = str(
            existing.get(
                "status",
                ""
            )
        ).strip()

        if current_status != "artwork_ready":

            return jsonify({
                "ok": True,
                "claimed": False,
                "release_mbid": release_mbid,
                "status": current_status,
            })

        existing["status"] = "running"

        existing["started_at"] = (
            datetime.now().isoformat(
                timespec="seconds"
            )
        )

        save_harmony_completions(
            completions
        )

    print(
        "Harmony release job claimed: "
        f"{release_mbid}"
    )

    return jsonify({
        "ok": True,
        "claimed": True,
        "release_mbid": release_mbid,
        "status": "running",
    })


