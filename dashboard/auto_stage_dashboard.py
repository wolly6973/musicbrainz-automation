def check_musicbrainz_barcode(
    barcode,
    album_title=None,
    artist_name=None
):
    """
    Check MusicBrainz for an existing release.

    Matching order:
        1. Exact barcode match
        2. Artist + album title fallback

    Returns:
        True  = release found
        False = successful lookup, release not found
        None  = lookup failed after retries
    """

    def normalize_text(value):

        if not value:
            return ""

        value = str(
            value
        ).lower()

        value = re.sub(
            r"[^a-z0-9]+",
            " ",
            value
        )

        return " ".join(
            value.split()
        )

    def musicbrainz_request(
        params
    ):

        url = (
            f"{MUSICBRAINZ_API}/release/"
        )

        for attempt in range(
            1,
            MB_MAX_RETRIES + 1
        ):

            wait_for_musicbrainz()

            try:

                response = session.get(
                    url,
                    params=params,
                    timeout=30
                )

                if response.status_code == 200:

                    return response.json()

                if response.status_code in RETRY_STATUS_CODES:

                    delay = (
                        min(
                            30,
                            2 ** attempt
                        )
                        + random.uniform(
                            0,
                            1
                        )
                    )

                    add_scan_log(
                        f"    MusicBrainz returned HTTP "
                        f"{response.status_code}. "
                        f"Retrying in {delay:.1f}s "
                        f"(attempt {attempt}/"
                        f"{MB_MAX_RETRIES})..."
                    )

                    if attempt < MB_MAX_RETRIES:

                        time.sleep(
                            delay
                        )

                        continue

                    return None

                add_scan_log(
                    f"    MusicBrainz returned HTTP "
                    f"{response.status_code}. "
                    f"Not retrying."
                )

                return None

            except requests.RequestException as exc:

                reset_http_session()

                if attempt >= MB_MAX_RETRIES:

                    add_scan_log(
                        f"    MusicBrainz request failed "
                        f"after {MB_MAX_RETRIES} attempts: "
                        f"{exc}"
                    )

                    return None

                delay = (
                    min(
                        30,
                        2 ** attempt
                    )
                    + random.uniform(
                        0,
                        1
                    )
                )

                add_scan_log(
                    f"    MusicBrainz request error: "
                    f"{exc}. "
                    f"Retrying in {delay:.1f}s "
                    f"(attempt {attempt}/"
                    f"{MB_MAX_RETRIES})..."
                )

                time.sleep(
                    delay
                )

        return None

    # --------------------------------------------------------
    # First: exact barcode lookup
    # --------------------------------------------------------

    if barcode:

        barcode_data = musicbrainz_request({
            "query": f"barcode:{barcode}",
            "fmt": "json",
            "limit": 1
        })

        if barcode_data is None:

            return None

        releases = barcode_data.get(
            "releases",
            []
        )

        if releases:

            return True

    # --------------------------------------------------------
    # Second: artist + album title fallback
    # --------------------------------------------------------

    if not album_title or not artist_name:

        return False

    artist_normalized = normalize_text(
        artist_name
    )

    title_normalized = normalize_text(
        album_title
    )

    if not artist_normalized or not title_normalized:

        return False

    fallback_query = (
        f'artist:"{artist_name}" '
        f'release:"{album_title}"'
    )

    add_scan_log(
        "    UPC not found. "
        "Trying artist/title match..."
    )

    fallback_data = musicbrainz_request({
        "query": fallback_query,
        "fmt": "json",
        "limit": 10
    })

    if fallback_data is None:

        return None

    fallback_releases = fallback_data.get(
        "releases",
        []
    )

    for release in fallback_releases:

        release_title = normalize_text(
            release.get(
                "title",
                ""
            )
        )

        if release_title != title_normalized:

            continue

        release_artist_match = False

        for artist_credit in release.get(
            "artist-credit",
            []
        ):

            artist = artist_credit.get(
                "artist",
                {}
            )

            candidate_artist = normalize_text(
                artist.get(
                    "name",
                    ""
                )
            )

            if candidate_artist == artist_normalized:

                release_artist_match = True
                break

        if release_artist_match:

            return True

    return False



