@app.route(
    "/harmony-release-complete",
    methods=["POST"]
)
def harmony_release_complete():

    data = request.get_json(
        silent=True
    ) or {}

    release_mbid = str(
        data.get(
            "release_mbid",
            ""
        )
    ).strip()

    deezer = str(
        data.get(
            "deezer",
            ""
        )
    ).strip()

    gtin = str(
        data.get(
            "gtin",
            ""
        )
    ).strip()

    artwork = data.get(
        "artwork"
    )

    if not release_mbid:

        return jsonify({
            "ok": False,
            "error": "Missing release_mbid",
        }), 400

    if not re.fullmatch(
        r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}",
        release_mbid,
    ):

        return jsonify({
            "ok": False,
            "error": "Invalid release_mbid",
        }), 400

    if artwork is not None and not isinstance(
        artwork,
        list
    ):

        return jsonify({
            "ok": False,
            "error": "Invalid artwork payload",
        }), 400

    with harmony_completion_lock:

        completions = get_harmony_completions()

        existing = next(
            (
                item
                for item in completions
                if item.get("release_mbid") == release_mbid
            ),
            None,
        )

        # ----------------------------------------------------
        # ARTWORK NOTIFICATION
        # ----------------------------------------------------
        if isinstance(
            artwork,
            list
        ):

            if existing:

                existing["deezer"] = (
                    deezer or
                    existing.get(
                        "deezer",
                        ""
                    )
                )

                existing["gtin"] = (
                    gtin or
                    existing.get(
                        "gtin",
                        ""
                    )
                )

                existing["artwork"] = artwork

                current_status = str(
                    existing.get(
                        "status",
                        ""
                    )
                ).strip()

                if current_status in {
                    "detected",
                    "waiting_for_artwork",
                }:

                    existing["status"] = (
                        "artwork_ready"
                    )

                    existing["artwork_ready_at"] = (
                        datetime.now().isoformat(
                            timespec="seconds"
                        )
                    )

                save_harmony_completions(
                    completions
                )

                print()
                print("========================================")
                print("HARMONY ARTWORK RECEIVED")
                print("========================================")
                print(
                    f"Release MBID: {release_mbid}"
                )
                print(
                    f"Artwork items: {len(artwork)}"
                )
                print(
                    f"Status:       "
                    f"{existing.get('status', '')}"
                )
                print("========================================")
                print()

                return jsonify({
                    "ok": True,
                    "duplicate": False,
                    "artwork_received": True,
                    "release_mbid": release_mbid,
                    "artwork_count": len(artwork),
                    "status": existing.get(
                        "status",
                        ""
                    ),
                })

            # Artwork arrived before the initial notification.
            completion = {
                "release_mbid": release_mbid,
                "deezer": deezer,
                "gtin": gtin,
                "artwork": artwork,
                "status": "artwork_ready",
                "detected_at": datetime.now().isoformat(
                    timespec="seconds"
                ),
                "artwork_ready_at": datetime.now().isoformat(
                    timespec="seconds"
                ),
            }

            completions.append(
                completion
            )

            save_harmony_completions(
                completions
            )

            print()
            print("========================================")
            print("HARMONY ARTWORK RECEIVED")
            print("========================================")
            print(
                f"Release MBID: {release_mbid}"
            )
            print(
                f"Artwork items: {len(artwork)}"
            )
            print(
                "Status:       artwork_ready"
            )
            print("========================================")
            print()

            return jsonify({
                "ok": True,
                "duplicate": False,
                "artwork_received": True,
                "release_mbid": release_mbid,
                "artwork_count": len(artwork),
                "status": "artwork_ready",
            })

        # ----------------------------------------------------
        # INITIAL RELEASE COMPLETION NOTIFICATION
        # ----------------------------------------------------
        if existing:

            print(
                "Harmony release completion already recorded: "
                f"{release_mbid}"
            )

            return jsonify({
                "ok": True,
                "duplicate": True,
                "release_mbid": release_mbid,
                "status": existing.get(
                    "status",
                    ""
                ),
            })

        completion = {
            "release_mbid": release_mbid,
            "deezer": deezer,
            "gtin": gtin,
            "status": "detected",
            "detected_at": datetime.now().isoformat(
                timespec="seconds"
            ),
        }

        completions.append(
            completion
        )

        save_harmony_completions(
            completions
        )

    print()
    print("========================================")
    print("HARMONY RELEASE COMPLETION DETECTED")
    print("========================================")
    print(
        f"Release MBID: {release_mbid}"
    )
    print(
        f"Deezer:       {deezer}"
    )
    print(
        f"GTIN:         {gtin}"
    )
    print(
        "Status:       detected"
    )
    print("========================================")
    print()

    return jsonify({
        "ok": True,
        "duplicate": False,
        "release_mbid": release_mbid,
        "status": "detected",
    })


