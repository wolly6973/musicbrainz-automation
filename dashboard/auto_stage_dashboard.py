def load_import_stats():
    """
    Load persistent import statistics.

    The file is intentionally simple JSON so it is easy to inspect
    or back up manually.
    """

    default_stats = {
        "total_unique_sent": 0,
        "total_actions": 0,
        "imports": []
    }

    try:

        if not os.path.exists(IMPORT_STATS_FILE):
            return default_stats

        with open(
            IMPORT_STATS_FILE,
            "r",
            encoding="utf-8"
        ) as file:

            data = json.load(file)

        if not isinstance(data, dict):
            return default_stats

        data.setdefault(
            "total_unique_sent",
            0
        )

        data.setdefault(
            "total_actions",
            0
        )

        data.setdefault(
            "imports",
            []
        )

        return data

    except Exception:

        return default_stats


def save_import_stats(stats):
    """
    Atomically save persistent import statistics.
    """

    directory = os.path.dirname(
        IMPORT_STATS_FILE
    )

    os.makedirs(
        directory,
        exist_ok=True
    )

    temp_file = (
        f"{IMPORT_STATS_FILE}.tmp"
    )

    with open(
        temp_file,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            stats,
            file,
            indent=2
        )

    os.replace(
        temp_file,
        IMPORT_STATS_FILE
    )


def get_import_stats():
    """
    Return a copy of the persistent statistics.
    """

    with import_stats_lock:

        stats = load_import_stats()

        return {
            "total_unique_sent": stats.get(
                "total_unique_sent",
                0
            ),
            "total_actions": stats.get(
                "total_actions",
                0
            ),
            "imports": list(
                stats.get(
                    "imports",
                    []
                )
            )
        }


def record_import(
    artist_name,
    artist_id,
    album_id,
    album_title,
    upc
):
    """
    Record that a release was successfully staged for MusicBrainz.

    The lifetime unique count is deduplicated by Deezer album ID.

    total_actions counts every successful Auto-Stage action.

    Returns:

        {
            "recorded": True/False,
            "unique": True/False,
            "total_unique_sent": N,
            "total_actions": N
        }
    """

    global current_scan_import_count

    unique_key = (
        f"deezer_album:{album_id}"
        if album_id
        else f"upc:{upc}"
    )

    with import_stats_lock:

        stats = load_import_stats()

        imports = stats.setdefault(
            "imports",
            []
        )

        now = datetime.now().astimezone().isoformat(
            timespec="seconds"
        )

        stats["total_actions"] = (
            stats.get(
                "total_actions",
                0
            ) + 1
        )

        already_sent = any(
            item.get("unique_key") == unique_key
            for item in imports
        )

        if not already_sent:

            stats["total_unique_sent"] = (
                stats.get(
                    "total_unique_sent",
                    0
                ) + 1
            )

            imports.append({
                "unique_key": unique_key,
                "timestamp": now,
                "artist_name": artist_name,
                "artist_id": str(artist_id),
                "album_id": str(album_id),
                "album_title": album_title,
                "upc": upc
            })

            unique = True

        else:

            unique = False

        save_import_stats(
            stats
        )

    if unique:

        with scan_lock:

            if unique_key not in current_scan_import_keys:

                current_scan_import_keys.add(
                    unique_key
                )

                current_scan_import_count += 1

    return {
        "recorded": True,
        "unique": unique,
        "total_unique_sent": stats.get(
            "total_unique_sent",
            0
        ),
        "total_actions": stats.get(
            "total_actions",
            0
        )
    }


