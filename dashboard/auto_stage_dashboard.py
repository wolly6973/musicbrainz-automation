def perform_scan(
    artist_id,
    artist_name,
    artist_query,
    expected_releases=None,
    selected_types=None,
    resume_state=None
):
    """
    Perform the complete Deezer -> UPC -> MusicBrainz scan.

    This runs in a background thread so the web page remains
    responsive and can display live progress.
    """

    global current_data, musicbrainz_scan_cache, musicbrainz_scan_stats

    if selected_types is None:
        selected_types = ["album", "ep", "single"]
    selected_types = [item for item in selected_types if item in {"album", "single", "ep"}]
    if not selected_types:
        selected_types = ["album", "ep", "single"]
    if resume_state:
        selected_types = [
            item for item in resume_state.get("selected_types", selected_types)
            if item in {"album", "single", "ep"}
        ] or selected_types

    set_scan_running(True)
    clear_scan_log()
    reset_scan_import_counter()
    musicbrainz_scan_cache = {}
    musicbrainz_scan_stats = {"requests": 0, "cache_hits": 0}

    try:
        add_scan_log(
            f'Starting scan for "{artist_name}" '
            f"(Deezer ID: {artist_id})"
        )
        type_labels = {"album": "Albums", "ep": "EPs", "single": "Singles"}
        selected_labels = [type_labels[item] for item in selected_types]
        add_scan_log("Release types selected: " + ", ".join(selected_labels))
        add_scan_log("")

        if resume_state and isinstance(resume_state.get("scan_catalog"), list) and resume_state.get("scan_catalog"):
            albums = list(resume_state["scan_catalog"])
            start_index = max(0, min(len(albums), int(resume_state.get("next_index", 0) or 0)))
            existing = int(resume_state.get("existing", 0) or 0)
            errors = int(resume_state.get("errors", 0) or 0)
            no_upc = int(resume_state.get("no_upc", 0) or 0)
            checked_count = int(resume_state.get("checked_count", 0) or 0)
            missing_items = list(resume_state.get("missing_items", []))
            total_albums = len(albums)
            add_scan_log(
                f"Resuming saved analysis at release {start_index + 1} "
                f"of {total_albums}; {start_index} release(s) already processed."
            )
            add_scan_log(
                f"Restored results: {len(missing_items)} missing, "
                f"{existing} existing, {errors} lookup errors, "
                f"{no_upc} without UPC."
            )
        else:
            add_scan_log("Retrieving release catalog from Deezer...")
            all_albums = get_deezer_albums(artist_id)
            albums, unknown_type_albums = filter_deezer_releases(all_albums, selected_types)
            add_scan_log("Retrieved " + str(len(all_albums)) + " total Deezer catalog entries.")
            add_scan_log("Matched " + str(len(albums)) + " selected release types.")
            if unknown_type_albums:
                unknown_counts = {}
                for item in unknown_type_albums:
                    raw_type = str(item.get("record_type") or "(missing)").strip().lower() or "(missing)"
                    unknown_counts[raw_type] = unknown_counts.get(raw_type, 0) + 1
                summary = ", ".join(str(kind) + "=" + str(count) for kind, count in sorted(unknown_counts.items()))
                add_scan_log("Skipped entries with unrecognized Deezer record_type: " + summary)
            start_index = 0
            existing = 0
            errors = 0
            no_upc = 0
            checked_count = 0
            missing_items = []
            total_albums = len(albums)

        expected_releases = total_albums
        add_scan_log("Expected releases to scan: " + str(expected_releases))
        add_scan_log("")

        if not albums:

            add_scan_log("")

            add_scan_log(
                "ERROR: No Deezer releases matched the selected types "
                f"({', '.join(selected_labels)})."
            )

            current_data = {
                "artist_query": artist_query,
                "resolved_name": artist_name,
                "artist_id": artist_id,
                "albums_count": 0,
                "checked_count": 0,
                "existing": 0,
                "errors": 0,
                "no_upc": 0,
                "missing_items": [],
                "selected_types": list(selected_types),
                "scan_cancelled": False,
                "status": (
                    "No Deezer releases matched the "
                    "selected release types."
                ),
                "candidates": []
            }

            return

        catalog_snapshot = [
            {
                "id": album.get("id"),
                "title": album.get("title", "Unknown Title"),
                "cover_medium": album.get("cover_medium", ""),
                "record_type": album.get("record_type")
            }
            for album in albums
        ]

        def save_progress(next_index, cancelled=False, status=None):
            global current_data
            current_data = {
                "artist_query": artist_query,
                "resolved_name": artist_name,
                "artist_id": artist_id,
                "albums_count": total_albums,
                "checked_count": checked_count,
                "existing": existing,
                "errors": errors,
                "no_upc": no_upc,
                "missing_items": list(missing_items),
                "selected_types": list(selected_types),
                "scan_cancelled": cancelled,
                "scan_complete": False,
                "next_index": next_index,
                "scan_catalog": catalog_snapshot,
                "status": status or (
                    f'Analysis of "{artist_name}" is in progress: '
                    f"{next_index} of {total_albums} releases processed."
                ),
                "candidates": []
            }
            save_last_scan()

        add_scan_log("")
        add_scan_log("Beginning UPC and MusicBrainz checks...")
        add_scan_log("")

        # ----------------------------------------------------
        # Check for cancellation before each release.
        # ----------------------------------------------------
        for index, album in enumerate(
            albums[start_index:],
            start=start_index + 1
        ):

            if is_scan_cancel_requested():

                add_scan_log("")

                add_scan_log(
                    "============================================================"
                )

                add_scan_log(
                    "SCAN CANCELLED"
                )

                add_scan_log(
                    f"Stopped before release {index} "
                    f"of {total_albums}."
                )
                add_scan_log(
                    f"Confirmed missing before cancellation: {len(missing_items)}"
                )
                add_scan_log(
                    "Partial results are being saved for display."
                )

                add_scan_log(
                    "============================================================"
                )

                save_progress(
                    index - 1,
                    cancelled=True,
                    status=(
                        f'Analysis of "{artist_name}" was cancelled before '
                        f"release {index} of {total_albums}. "
                        f"{index - 1} release(s) processed; "
                        f"{len(missing_items)} confirmed missing."
                    )
                )
                return

            album_id = album.get(
                "id"
            )

            title = album.get(
                "title",
                "Unknown Title"
            )

            cover_url = album.get(
                "cover_medium",
                ""
            )

            add_scan_log(
                f'[{index}/{total_albums}] '
                f'Checking "{title}"...'
            )

            # Retrieve UPC
            add_scan_log(
                "    Retrieving UPC from Deezer..."
            )

            upc = get_deezer_album_upc(
                album_id
            )

            if not upc:

                no_upc += 1

                add_scan_log(
                    "    No UPC found. "
                    "Skipping MusicBrainz lookup."
                )

                add_scan_log("")

                # This release is fully processed even though it had no UPC.
                # Persist the next index before continuing the loop.
                save_progress(index, cancelled=False)

                continue

            checked_count += 1

            add_scan_log(
                f"    UPC: {upc}"
            )

            # MusicBrainz lookup
            add_scan_log(
                "    Checking MusicBrainz..."
            )

            mb_result = check_musicbrainz_barcode(
                upc,
                album_title=title,
                artist_name=artist_name
            )

            # Found
            if mb_result is True:

                existing += 1

                add_scan_log(
                    "    MusicBrainz: FOUND"
                )

            # Missing
            elif mb_result is False:

                add_scan_log(
                    "    MusicBrainz: MISSING"
                )

                deezer_link = (
                    f"https://deezer.com/album/"
                    f"{album_id}"
                )

                encoded_url = (
                    urllib.parse.quote(
                        deezer_link,
                        safe=""
                    )
                )

                harmony_url = (
                    f"{HARMONY_URL}/release"
                    f"?url={encoded_url}"
                )

                spaced_url = re.sub(
                    r"([:/?.=&])",
                    r" \1",
                    harmony_url
                )

                missing_items.append({
                    "title": title,
                    "upc": upc,
                    "cover": cover_url,
                    "album_id": album_id,
                    "harmony_link": (
                        f"/mb-seed?url="
                        f"{urllib.parse.quote(deezer_link, safe='')}"
                    ),
                    "display_url": spaced_url
                })

            # Lookup error
            else:

                errors += 1

                add_scan_log(
                    "    MusicBrainz: LOOKUP ERROR"
                )

            add_scan_log("")

            # Persist only after the current release has a final result.
            # If interrupted mid-request, the prior checkpoint causes a retry.
            save_progress(index, cancelled=False)

        # A cancellation can arrive while the final release request is
        # in flight. Check again before reporting a complete scan.
        if is_scan_cancel_requested():
            add_scan_log("")
            add_scan_log("============================================================")
            add_scan_log("SCAN CANCELLED")
            add_scan_log(
                f"Stopped after processing release {total_albums} "
                f"of {total_albums}."
            )
            add_scan_log(
                f"Confirmed missing before cancellation: {len(missing_items)}"
            )
            add_scan_log("Partial results are being saved for display.")
            add_scan_log("============================================================")

            save_progress(
                total_albums,
                cancelled=True,
                status=(
                    f'Analysis of "{artist_name}" was cancelled after '
                    f"processing all {total_albums} releases. "
                    f"{len(missing_items)} confirmed missing."
                )
            )
            return

        # Final summary
        add_scan_log(
            "============================================================"
        )

        add_scan_log(
            "SCAN COMPLETE"
        )

        add_scan_log(
            f"Albums retrieved: {total_albums}"
        )

        add_scan_log(
            f"Albums checked by UPC: {checked_count}"
        )

        add_scan_log(
            f"Albums without UPC: {no_upc}"
        )

        add_scan_log(
            f"Existing on MusicBrainz: {existing}"
        )

        add_scan_log(
            f"Confirmed missing: "
            f"{len(missing_items)}"
        )

        add_scan_log(
            f"Lookup errors: {errors}"
        )

        add_scan_log(
            f"MusicBrainz HTTP requests: {musicbrainz_scan_stats['requests']}"
        )

        add_scan_log(
            f"MusicBrainz cache hits: {musicbrainz_scan_stats['cache_hits']}"
        )

        add_scan_log(
            "============================================================"
        )

        current_data = {
            "artist_query": artist_query,
            "resolved_name": artist_name,
            "artist_id": artist_id,
            "albums_count": total_albums,
            "checked_count": checked_count,
            "existing": existing,
            "errors": errors,
            "no_upc": no_upc,
            "missing_items": missing_items,
            "selected_types": list(selected_types),
            "scan_cancelled": False,
            "scan_complete": True,
            "status": (
                f'Scan completed for "{artist_name}"! '
                f"Discovered {len(missing_items)} "
                f"missing library releases."
            ),
            "candidates": []
        }

        save_last_scan()

    except Exception as exc:

        add_scan_log("")

        add_scan_log(
            "============================================================"
        )

        add_scan_log(
            f"FATAL ERROR: {exc}"
        )

        add_scan_log(
            "============================================================"
        )

        current_data = {
            "artist_query": artist_query,
            "resolved_name": artist_name,
            "artist_id": artist_id,
            "albums_count": 0,
            "checked_count": 0,
            "existing": 0,
            "errors": 1,
            "no_upc": 0,
            "missing_items": [],
            "status": f"Scan failed: {exc}",
            "candidates": []
        }

    finally:

        set_scan_running(False)


