def create_auto_stage_seed(deezer_url):
    """
    Perform the final UPC duplicate check, then obtain Harmony's
    exact MusicBrainz seed.

    Returns:
        (html, status_code, message)
    """

    parsed = urllib.parse.urlparse(deezer_url)
    query = urllib.parse.parse_qs(parsed.query)

    album_id = None

    match = re.search(r"/album/(\d+)", parsed.path)
    if match:
        album_id = match.group(1)

    if not album_id and query.get("id"):
        album_id = query["id"][0]

    if not album_id:
        return None, 400, "Could not determine Deezer album ID."

    # --------------------------------------------------------
    # Get UPC again immediately before staging.
    # --------------------------------------------------------
    upc = get_deezer_album_upc(album_id)

    if not upc:
        return None, 400, (
            f"Could not determine UPC for Deezer album {album_id}."
        )

    # --------------------------------------------------------
    # FINAL MusicBrainz duplicate check.
    #
    # True  = exists
    # False = missing
    # None  = lookup failure
    # --------------------------------------------------------
    mb_exists = check_musicbrainz_barcode(upc)

    if mb_exists is True:
        return None, 409, (
            f"MusicBrainz already contains a release with UPC {upc}."
        )

    if mb_exists is None:
        return None, 502, (
            f"MusicBrainz UPC check failed for {upc}. "
            "Nothing was staged."
        )

    # --------------------------------------------------------
    # Only now ask Harmony to generate the exact seed.
    # --------------------------------------------------------
    seed, error = get_harmony_musicbrainz_seed(deezer_url)

    if error:
        return None, 502, error

    # --------------------------------------------------------
    # Safety check: make sure Harmony's seed contains the same
    # UPC that we just verified as missing.
    # --------------------------------------------------------
    seed_barcodes = [
        value
        for name, value in seed["fields"]
        if name == "barcode"
    ]

    if upc not in seed_barcodes:
        return None, 502, (
            "Harmony's generated seed does not contain the expected "
            f"UPC {upc}. Nothing was staged."
        )

    # --------------------------------------------------------
    # Record the action only after:
    #   1. final duplicate check succeeded
    #   2. Harmony successfully generated the seed
    # --------------------------------------------------------
    album_data = get_deezer_album(album_id)

    artist_name = ""
    artist_id = ""
    album_title = ""

    if album_data:
        album_title = str(
            album_data.get("title", "")
        ).strip()

        artist_data = album_data.get("artist") or {}

        artist_name = str(
            artist_data.get("name", "")
        ).strip()

        artist_id = str(
            artist_data.get("id", "")
        ).strip()

    record_import(
        artist_name=artist_name,
        artist_id=artist_id,
        album_id=album_id,
        album_title=album_title,
        upc=upc,
    )

    return (
        build_musicbrainz_seed_page(
            seed,
            deezer_url,
            album_id,
        ),
        200,
        None,
    )


