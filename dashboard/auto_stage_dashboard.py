class HiddenInputParser(HTMLParser):
    """Extract hidden form inputs from Harmony's release-seeder form."""

    def __init__(self):
        super().__init__()
        self.in_seed_form = False
        self.seed_action = None
        self.fields = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)

        if tag.lower() == "form":
            if attrs.get("name") == "release-seeder":
                self.in_seed_form = True
                self.seed_action = attrs.get("action")

        elif tag.lower() == "input" and self.in_seed_form:
            if attrs.get("type", "").lower() == "hidden":
                name = attrs.get("name")
                value = attrs.get("value", "")

                if name:
                    self.fields.append((name, value))

    def handle_endtag(self, tag):
        if tag.lower() == "form" and self.in_seed_form:
            self.in_seed_form = False


def get_harmony_musicbrainz_seed(deezer_url):
    """
    Fetch Harmony's release page and extract the exact MusicBrainz
    release-seeder form generated by Harmony.
    """

    try:
        response = requests.get(
            f"{HARMONY_URL}/release",
            params={
                "url": deezer_url,
                "category": "all",
            },
            timeout=30,
        )

        response.raise_for_status()

    except requests.RequestException as exc:
        return None, f"Harmony request failed: {exc}"

    parser = HiddenInputParser()
    parser.feed(response.text)

    if not parser.fields:
        return None, (
            "Harmony did not return a release-seeder form. "
            "The release may not have been resolved by Harmony."
        )

    if not parser.seed_action:
        return None, "Harmony release-seeder form has no target action."

    if not parser.seed_action.startswith(
        "https://musicbrainz.org/release/add"
    ):
        return None, (
            "Harmony returned an unexpected MusicBrainz seed target: "
            f"{parser.seed_action}"
        )

    return {
        "action": parser.seed_action,
        "fields": parser.fields,
    }, None


def build_musicbrainz_seed_page(seed, deezer_url, album_id):
    """
    Build a browser page that automatically POSTs Harmony's exact
    seed fields to the MusicBrainz Release Editor.

    The final MusicBrainz edit is NOT submitted automatically.
    MusicBrainz displays the Release Editor for user review.
    """

    rewritten_fields = []

    for name, value in seed["fields"]:
        if isinstance(value, str):
            value = value.replace(
                "http://localhost:8000",
                HARMONY_BROWSER_URL,
            ).replace(
                "http://harmony:8000",
                HARMONY_BROWSER_URL,
            )

        rewritten_fields.append((name, value))

    html_parts = [
        "<!doctype html>",
        "<html>",
        "<head>",
        '<meta charset="utf-8">',
        "<title>Auto-Stage Import</title>",
        """
        <style>
            body {
                font-family: system-ui, sans-serif;
                max-width: 760px;
                margin: 60px auto;
                padding: 0 20px;
                line-height: 1.5;
            }
            .box {
                border: 1px solid #ccc;
                border-radius: 10px;
                padding: 24px;
            }
            .status {
                font-size: 18px;
                font-weight: 600;
            }
            button {
                padding: 10px 18px;
                font-size: 16px;
                cursor: pointer;
            }
        </style>
        """,
        "</head>",
        "<body>",
        '<div class="box">',
        "<h1>Auto-Stage Import</h1>",
        f"<p>Preparing MusicBrainz Release Editor for album "
        f"<strong>{escape(str(album_id))}</strong>.</p>",
        '<p class="status">MusicBrainz Release Editor is ready for review.</p>',
        """
        <form id="seed-form"
              action="https://musicbrainz.org/release/add?skip_confirmation=1"
              method="post">
        """,
    ]

    for name, value in rewritten_fields:
        html_parts.append(
            f'<input type="hidden" name="{escape(name, quote=True)}" '
            f'value="{escape(str(value), quote=True)}">'
        )

    html_parts.extend([
        "</form>",
        """
        <noscript>
            <p>JavaScript is disabled. Click the button below.</p>
            <button type="submit" form="seed-form">
                Continue to MusicBrainz
            </button>
        </noscript>
        """,
        "</div>",
        """
        <script>
            window.setTimeout(function() {
                document.getElementById("seed-form").submit();
            }, 150);
        </script>
        """,
        "</body>",
        "</html>",
    ])

    return "\n".join(html_parts)


def create_auto_stage_seed(deezer_url):
    """
    Perform the final UPC duplicate check, then obtain Harmony's
    exact MusicBrainz seed.

    Returns:
        (html, status_code, message)
    """

    parsed = urllib.parse.urlparse(deezer_url)
    query = urllib.parse.parse_qs(parsed.query)

    album_id = None

    match = re.search(r"/album/(\d+)", parsed.path)
    if match:
        album_id = match.group(1)

    if not album_id and query.get("id"):
        album_id = query["id"][0]

    if not album_id:
        return None, 400, "Could not determine Deezer album ID."

    # --------------------------------------------------------
    # Get UPC again immediately before staging.
    # --------------------------------------------------------
    upc = get_deezer_album_upc(album_id)

    if not upc:
        return None, 400, (
            f"Could not determine UPC for Deezer album {album_id}."
        )

    # --------------------------------------------------------
    # FINAL MusicBrainz duplicate check.
    #
    # True  = exists
    # False = missing
    # None  = lookup failure
    # --------------------------------------------------------
    mb_exists = check_musicbrainz_barcode(upc)

    if mb_exists is True:
        return None, 409, (
            f"MusicBrainz already contains a release with UPC {upc}."
        )

    if mb_exists is None:
        return None, 502, (
            f"MusicBrainz UPC check failed for {upc}. "
            "Nothing was staged."
        )

    # --------------------------------------------------------
    # Only now ask Harmony to generate the exact seed.
    # --------------------------------------------------------
    seed, error = get_harmony_musicbrainz_seed(deezer_url)

    if error:
        return None, 502, error

    # --------------------------------------------------------
    # Safety check: make sure Harmony's seed contains the same
    # UPC that we just verified as missing.
    # --------------------------------------------------------
    seed_barcodes = [
        value
        for name, value in seed["fields"]
        if name == "barcode"
    ]

    if upc not in seed_barcodes:
        return None, 502, (
            "Harmony's generated seed does not contain the expected "
            f"UPC {upc}. Nothing was staged."
        )

    # --------------------------------------------------------
    # Record the action only after:
    #   1. final duplicate check succeeded
    #   2. Harmony successfully generated the seed
    # --------------------------------------------------------
    album_data = get_deezer_album(album_id)

    artist_name = ""
    artist_id = ""
    album_title = ""

    if album_data:
        album_title = str(
            album_data.get("title", "")
        ).strip()

        artist_data = album_data.get("artist") or {}

        artist_name = str(
            artist_data.get("name", "")
        ).strip()

        artist_id = str(
            artist_data.get("id", "")
        ).strip()

    record_import(
        artist_name=artist_name,
        artist_id=artist_id,
        album_id=album_id,
        album_title=album_title,
        upc=upc,
    )

    return (
        build_musicbrainz_seed_page(
            seed,
            deezer_url,
            album_id,
        ),
        200,
        None,
    )


